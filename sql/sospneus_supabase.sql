CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  cargo TEXT NOT NULL DEFAULT 'operador_base',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS pneus (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medida TEXT NOT NULL,
  aro INTEGER NOT NULL,
  marca TEXT NOT NULL,
  modelo TEXT NOT NULL,
  tipo_terreno TEXT NOT NULL,
  indice_carga_vel TEXT NOT NULL,
  selo_inmetro TEXT NOT NULL,
  preco_unitario NUMERIC(10,2) NOT NULL,
  preco_kit4 NUMERIC(10,2) NOT NULL,
  estoque INTEGER NOT NULL DEFAULT 8,
  aplicacao_carros TEXT NOT NULL,
  destaque BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS chamados_socorro (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo TEXT NOT NULL UNIQUE,
  tipo_emergencia TEXT NOT NULL,
  distancia_km NUMERIC(6,2) NOT NULL DEFAULT 5,
  tempo_chegada_min INTEGER NOT NULL DEFAULT 25,
  valor_total_estimado NUMERIC(10,2) NOT NULL,
  nome_motorista TEXT NOT NULL,
  telefone TEXT NOT NULL,
  localizacao_referencia TEXT NOT NULL,
  veiculo_medida TEXT NOT NULL,
  consentimento_lgpd BOOLEAN NOT NULL DEFAULT TRUE,
  status TEXT NOT NULL DEFAULT 'Viatura Acionada',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS solicitacoes_lgpd (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo TEXT NOT NULL UNIQUE,
  nome_titular TEXT NOT NULL,
  email_titular TEXT NOT NULL,
  tipo_direito TEXT NOT NULL,
  detalhes TEXT,
  status TEXT NOT NULL DEFAULT 'Recebido',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE pneus ENABLE ROW LEVEL SECURITY;
ALTER TABLE chamados_socorro ENABLE ROW LEVEL SECURITY;
ALTER TABLE solicitacoes_lgpd ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Leitura publica de pneus" ON pneus FOR SELECT USING (true);
CREATE POLICY "Apenas backend gerencia chamados" ON chamados_socorro FOR ALL USING (false);
